sidebar_interface(Index) ->
	maps:get(Index, ?SIDEBAR_INTERFACES).

sidebar_interfaces() ->
	?SIDEBAR_INTERFACES.

skill_id(Key) ->
	maps:get(Key, ?SKILLS).

decoder_module(OperationCode) ->
	DecoderList = maps:to_list(?DECODERS),
	case lists:search(fun({Codes, _}) -> lists:member(OperationCode, Codes) end, DecoderList) of
		{value, {_, Name}} ->
			Name;
		_ ->
			undefined
	end.

decoder_length(OperationCode) ->
	maps:get(OperationCode, ?DECODER_LENGTHS, 0).

encoder_code(Module) ->
	maps:get(Module, ?ENCODERS, undefined).
